"""Generate Lab-verified agent trajectories for fine-tuning.

    python training/agent/make_data.py --per-pair 3 --workers 6

Every trajectory is executed for real through the web terminal's own Python
shim (the same code evals/agent/run_eval.py scores), so every tool output in
the data is the true output, and every final answer is written from the Lab's
actual result. Nothing is generated by an LLM.

Leakage guard: families and tickers are disjoint from evals/agent (asserted).
Output: data/train.jsonl and data/dev.jsonl (dev = held-out tickers), one
{"messages", "tools", "meta"} record per line, OpenAI chat format.
"""

from __future__ import annotations

import argparse
import inspect
import itertools
import json
import random
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "evals" / "agent"))
sys.path.insert(0, str(HERE))
import common  # noqa: E402
import families as TEST_F  # noqa: E402
import train_families as F  # noqa: E402

assert not set(F.FAMILIES) & set(TEST_F.FAMILIES), "training families overlap the test set"
assert not (set(F.TRAIN_SYMBOLS) | set(F.DEV_SYMBOLS)) & F.TEST_SYMBOLS, "training tickers overlap the test set"
assert not set(F.TRAIN_SYMBOLS) & set(F.DEV_SYMBOLS)

CASH_SUFFIX = [" I only care whether it makes money in absolute terms, not whether it beats holding.",
               " Compare it to cash, not to buy-and-hold: I want to know if it's profitable at all."]


def fmt_list(xs):
    xs = [f"{x:g}" if isinstance(x, float) else str(x) for x in xs]
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1]


def call(cid, name, args):
    return {"id": cid, "type": "function", "function": {"name": name, "arguments": json.dumps(args)}}


def signal_code(spec, sym, vs, grid, buggy=False, lab_kw=True):
    src = inspect.getsource(spec["signal"]).rstrip()
    if buggy:
        src = src.replace("d.close", 'd["Close"]')
    lab_args = f"'{sym}', vs='cash'" if (vs == "cash" and lab_kw) else f"'{sym}'"
    combos = 1
    for v in grid.values():
        combos *= len(v)
    run = (f"L.sweep({spec['signal'].__name__}, " + ", ".join(f"{k}={v!r}" for k, v in grid.items()) + ")") if combos > 1 \
        else (f"L.run({spec['signal'].__name__}, " + ", ".join(f"{k}={v[0]!r}" for k, v in grid.items()) + ")")
    return f"{src}\n\nL = lab({lab_args})\n{run}\nprint(L.check())", combos


_PATH = re.compile(r'File "[^"]*?[\\/](?:site-packages|src)[\\/]([^"]+)"')


def clean(out: str) -> str:
    """Make tracebacks look like the browser's (Pyodide) and keep local paths out of the data."""
    out = _PATH.sub(lambda m: 'File "/lib/python3.12/site-packages/' + m.group(1).replace("\\", "/") + '"', out)
    return re.sub(r"Python 3\.\d+\.\d+", "Python 3.12.7", out)


def pct(x):
    return f"{x:.3f}" if x >= 0.001 else "<0.001"


def final_answer(rng, sym, vs, n_var, L, r, holdout, vague_note):
    from dataclasses import replace
    from tokio_ai.lab import _label
    best = r.best
    if n_var == 1:  # a single run is reported as "strategy"; name it by its signal instead
        best = replace(best, name=_label(L.runs[0]))
    idx = L.runs[0].returns.index
    span = f"{sym} daily bars {idx[0].date()} to {idx[-1].date()} ({best.n_bars} bars, the first 75% of the history)"
    base = "against holding it at the same exposure" if vs == "market" else "against cash"
    lines = []
    if r.verdict == "SIGNIFICANT":
        lines.append(f"**SIGNIFICANT.** {best.name} beats {'holding ' + sym + ' at the same exposure' if vs == 'market' else 'cash'} "
                     + (f"even after correcting for the {n_var} variants tested." if n_var > 1 else "in its single test."))
    elif r.verdict == "NOT SIGNIFICANT":
        lines.append(rng.choice([f"**NOT SIGNIFICANT.** No variant beats {'holding ' + sym if vs == 'market' else 'cash'} once the {n_var} variant{'s' if n_var > 1 else ''} tested are accounted for.",
                                 f"**NOT SIGNIFICANT.** The evidence doesn't support this on {sym}."]))
    else:
        lines.append(f"**{r.verdict}.** The Lab won't call this a result: see the notes in the report.")
    if vague_note:
        lines.append(vague_note)
    nums = [f"corrected p = {pct(r.p_value)}",
            f"best variant {best.name}: Sharpe {best.sharpe:.2f} {'vs the market' if vs == 'market' else 'absolute'}",
            f"haircut Sharpe {best.haircut_sharpe:.2f}"]
    pbo = getattr(r.overfitting, "pbo", None) if r.overfitting is not None else None
    if n_var > 1 and pbo is not None:
        nums.append(f"probability of overfitting {pbo:.2f}")
    lines.append("- " + "\n- ".join(nums))
    lines.append(f"Sample: {span}; {n_var} variant{'s' if n_var > 1 else ''} tried, tested {base}, next-open fills, 10 bp costs.")
    if holdout is not None:
        lines.append(f"On the untouched last 25% ({holdout.best.n_bars} bars), {best.name} came out **{holdout.verdict.lower()}** "
                     f"(p = {pct(holdout.p_value)}, Sharpe {holdout.best.sharpe:.2f}). "
                     + ("It held up out of sample." if holdout.verdict == "SIGNIFICANT" else "So the in-sample result did not carry into the holdout; treat it as fragile."))
    if r.verdict == "SIGNIFICANT":
        tail = "This is a research result on past data, not a recommendation to trade it."
    elif vs == "market":
        tail = rng.choice([f"Any gains came from {sym}'s own move, not from the timing.",
                           "The timing rule doesn't add anything you can tell apart from luck."])
    else:
        tail = "Whatever it earned is not distinguishable from zero on this sample."
    lines.append(tail)
    return "\n\n".join(lines)


def build(task):
    """Run one trajectory through the shim. Returns a record, or None if it failed verification."""
    shim = build.shim
    rng = random.Random(task["seed"])
    fam, sym, vs, grid, question, vague_note, buggy = (task[k] for k in ("family", "symbol", "vs", "grid", "question", "vague_note", "buggy"))
    spec = F.FAMILIES[fam]
    shim["reset_agent"]()
    msgs = [{"role": "system", "content": common.system_prompt()}, {"role": "user", "content": question}]
    n = 0

    def tool(cid, out):
        msgs.append({"role": "tool", "tool_call_id": cid, "content": clean(out)})

    n += 1
    msgs.append({"role": "assistant", "content": rng.choice(["", "", f"Loading {sym}."]), "tool_calls": [call(f"c{n}", "get_prices", {"symbol": sym})]})
    tool(f"c{n}", shim["load_chart"](sym, common.chart_payload(sym)))

    code, n_var = signal_code(spec, sym, vs, grid, buggy=buggy)
    if buggy:
        n += 1
        msgs.append({"role": "assistant", "content": "", "tool_calls": [call(f"c{n}", "run_python", {"code": code})]})
        out = json.loads(shim["run_code"](code, 0))
        if out["ok"]:
            return None
        tool(f"c{n}", out["output"])
        code, _ = signal_code(spec, sym, vs, grid, lab_kw=False)
        fix = "The price columns are lowercase (`close`, not `Close`). Fixing and rerunning."
    else:
        fix = vague_note or ""
    n += 1
    msgs.append({"role": "assistant", "content": fix, "tool_calls": [call(f"c{n}", "run_python", {"code": code})]})
    out = json.loads(shim["run_code"](code, 0))
    if not out["ok"]:
        return None
    tool(f"c{n}", out["output"])

    L = shim["LABS"][sym]
    if len(L.runs) != n_var or L.vs != vs:
        return None
    r = L.check()
    holdout = None
    if r.verdict == "SIGNIFICANT":
        n += 1
        ft_code = "ho = L.final_test(L.best())\nprint(ho)"
        msgs.append({"role": "assistant", "content": "It passes in-sample. Running the chosen variant once on the untouched holdout.",
                     "tool_calls": [call(f"c{n}", "run_python", {"code": ft_code})]})
        out = json.loads(shim["run_code"](ft_code, 0))
        if not out["ok"]:
            return None
        tool(f"c{n}", out["output"])
        holdout = getattr(shim["NS"]["ho"], "report", shim["NS"]["ho"])
        if len(L.runs) != n_var:
            return None
    msgs.append({"role": "assistant", "content": final_answer(rng, sym, vs, n_var, L, r, holdout, vague_note)})
    meta = {k: task[k] for k in ("family", "symbol", "vs", "grid", "vague", "buggy", "split")}
    meta.update(verdict=r.verdict, p=round(float(r.p_value), 4), n_variants=n_var,
                holdout=None if holdout is None else holdout.verdict)
    return {"messages": msgs, "tools": common.TOOLS, "meta": meta}


def _init():
    build.shim = common.load_shim()


def tasks(per_pair: int, seed: int):
    rng = random.Random(seed)
    out = []
    for split, syms in (("train", F.TRAIN_SYMBOLS), ("dev", F.DEV_SYMBOLS)):
        for sym, fam in itertools.product(syms, F.FAMILIES):
            spec = F.FAMILIES[fam]
            for j in range(per_pair):
                vague = j == 0 and rng.random() < 0.5
                if vague:
                    grid, question, note = spec["vague_grid"], spec["vague"].format(sym=sym), spec["vague_note"]
                else:
                    grid = rng.choice(spec["grids"])
                    question = rng.choice(spec["q"]).format(sym=sym, **{k: fmt_list(v) for k, v in grid.items()})
                    note = None
                vs = "market"
                if not vague and rng.random() < 0.25:
                    vs, question = "cash", question + rng.choice(CASH_SUFFIX)
                out.append(dict(seed=rng.randrange(1 << 30), family=fam, symbol=sym, vs=vs, grid=grid, question=question,
                                vague=vague, vague_note=note, buggy=rng.random() < 0.15 and "d.close" in inspect.getsource(spec["signal"]), split=split))
    # drop exact duplicates (same question and grid)
    seen, uniq = set(), []
    for tk in out:
        key = (tk["symbol"], tk["question"], tk["vs"], tk["buggy"])
        if key not in seen:
            seen.add(key)
            uniq.append(tk)
    return uniq


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-pair", type=int, default=3)
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--seed", type=int, default=20261119)
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()
    todo = tasks(args.per_pair, args.seed)
    if args.limit:
        todo = todo[: args.limit]
    for sym in set(F.TRAIN_SYMBOLS) | set(F.DEV_SYMBOLS):
        common.chart_payload(sym)  # fetch once, before the workers start
    outdir = HERE / "data"
    outdir.mkdir(exist_ok=True)
    files = {s: (outdir / f"{s}.jsonl").open("w", encoding="utf-8") for s in ("train", "dev")}
    stats = {}
    from multiprocessing import Pool
    with Pool(args.workers, initializer=_init) as pool:
        for i, rec in enumerate(pool.imap_unordered(_safe_build, todo), 1):
            if rec is None:
                stats["rejected"] = stats.get("rejected", 0) + 1
                continue
            m = rec["meta"]
            files[m["split"]].write(json.dumps(rec) + "\n")
            k = (m["split"], m["verdict"])
            stats[k] = stats.get(k, 0) + 1
            if i % 25 == 0:
                print(i, "/", len(todo), stats, flush=True)
    for f in files.values():
        f.close()
    print("done", stats)


def _safe_build(task):
    try:
        return build(task)
    except Exception as e:  # a failed trajectory is dropped, never written
        print("drop", task["family"], task["symbol"], type(e).__name__, str(e)[:200], flush=True)
        return None


if __name__ == "__main__":
    main()
